create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null default 'member' check (role in ('admin','member')),
  timezone text not null check (timezone in ('Asia/Kolkata','America/Phoenix')),
  created_at timestamptz not null default now()
);

create or replace function public.is_member()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid()) $$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and role='admin') $$;

create table public.chapters (
  id bigint generated by default as identity primary key,
  chapter_number int unique not null check (chapter_number between 1 and 8),
  chapter_date date not null,
  title text not null,
  message text not null,
  song_title text,
  song_artist text,
  song_url text
);

create table public.questions (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references public.chapters(id) on delete cascade,
  question_text text not null,
  sort_order int not null default 0
);
create index questions_chapter_idx on public.questions(chapter_id);

create table public.responses (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.questions(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(question_id,user_id)
);
create index responses_question_idx on public.responses(question_id);

create table public.gallery_media (
  id uuid primary key default gen_random_uuid(),
  chapter_number int not null check (
    (chapter_number between 1 and 7) or chapter_number=8
  ),
  slot_number int not null,
  storage_path text not null unique,
  media_kind text not null check (media_kind in ('image','video')),
  original_name text,
  caption text not null default '',
  uploaded_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(chapter_number,slot_number),
  check (
    (chapter_number between 1 and 7 and slot_number between 1 and 3 and media_kind='image')
    or (chapter_number=8 and slot_number between 1 and 10)
  )
);

create table public.checklist_items (
  id bigint generated by default as identity primary key,
  group_name text not null,
  label text not null,
  sort_order int not null default 0
);
create table public.checklist_responses (
  item_id bigint not null references public.checklist_items(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  checked boolean not null default false,
  notes text not null default '',
  updated_at timestamptz not null default now(),
  primary key(item_id,user_id)
);

create table public.story_milestones (
  id bigint generated by default as identity primary key,
  sort_order int not null unique,
  title text not null,
  description text not null default '',
  event_date date
);

create table public.promises (
  id uuid primary key default gen_random_uuid(),
  content text not null,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.time_capsules (
  id uuid primary key default gen_random_uuid(),
  content text not null,
  created_by uuid not null references public.profiles(id) on delete cascade,
  reveal_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table public.app_settings (
  key text primary key,
  value text not null default '',
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);

